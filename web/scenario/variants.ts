import {
  line,
  ruby,
  type JapaneseLine,
  type MeaningQuestion,
  type ScenarioDefinition,
  type SpeakingPrompt,
} from "./content.ts";

export interface ScenarioVariant extends ScenarioDefinition {
  baseId: string;
  contentVersion: 1;
}
type Question = Omit<MeaningQuestion, "id">;
type Prompt = Omit<SpeakingPrompt, "id">;
function variant(
  baseId: string,
  title: string,
  dialogue: JapaneseLine[],
  listening: Question[],
  response: Prompt,
  transfer: Prompt,
  message: JapaneseLine,
  reading: Question[],
): ScenarioVariant {
  const id = `${baseId}-variant-b1`;
  return {
    id,
    baseId,
    contentVersion: 1,
    title,
    objective: transfer.context,
    listeningHeading: title,
    listeningFocus: "对话中的新条件",
    readingFocus: "消息中的具体安排",
    readingWords: [],
    transferFocus: transfer.title,
    dialogue: dialogue.map((value, index) => ({
      speaker: index % 2 ? "B" : "A",
      line: value,
    })),
    listeningQuestions: listening.map((q, i) => ({
      ...q,
      id: `${id}-listen-${i + 1}`,
    })),
    expressions: [],
    responsePrompts: [{ ...response, id: `${id}-response` }],
    transferPrompt: { ...transfer, id: `${id}-transfer` },
    readingMessage: message,
    readingQuestions: reading.map((q, i) => ({
      ...q,
      id: `${id}-read-${i + 1}`,
    })),
    readingSender: "情景消息",
    readingLabel: "变体 B · 练习设定",
  };
}
